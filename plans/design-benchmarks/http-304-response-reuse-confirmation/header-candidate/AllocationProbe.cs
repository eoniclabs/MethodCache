using System.Diagnostics;
using System.Net;
using System.Net.Http.Headers;
using System.Reflection;
using MethodCache.HttpCaching;
var merge = typeof(HttpCacheEntry).GetMethod("WithUpdatedHeaders", BindingFlags.Instance | BindingFlags.NonPublic)!.CreateDelegate<Func<HttpCacheEntry, HttpResponseMessage, DateTimeOffset, TimeSpan, HttpCacheEntry>>();
var entry = new HttpCacheEntry { RequestUri = "https://benchmark.invalid/revalidated", Method = "GET", Headers = new(StringComparer.OrdinalIgnoreCase) { ["Cache-Control"] = ["no-cache, max-age=3600"], ["ETag"] = ["\"fixed\""] }, ContentHeaders = new() { ["Content-Type"] = ["text/plain; charset=utf-8"] }, Content = [1,2,3,4] };
using var response = new HttpResponseMessage(HttpStatusCode.NotModified) { Content = new ByteArrayContent([]) };
response.Headers.CacheControl = new CacheControlHeaderValue { NoCache = true, MaxAge = TimeSpan.FromHours(1) };
response.Headers.ETag = new EntityTagHeaderValue("\"fixed\"");
var now=DateTimeOffset.UnixEpoch;
for (var i=0;i<10000;i++) merge(entry,response,now,default);
var before=GC.GetAllocatedBytesForCurrentThread();
var started=Stopwatch.GetTimestamp();
HttpCacheEntry? result=null;
const int count=50000;
for (var i=0;i<count;i++) result=merge(entry,response,now,default);
var ns=Stopwatch.GetElapsedTime(started).TotalNanoseconds/count;
var allocated=(GC.GetAllocatedBytesForCurrentThread()-before)/(double)count;
if(result!.Headers.Count!=2 || result.Content.Length!=4) throw new Exception("Invalid merged representation");
Console.WriteLine(System.Text.Json.JsonSerializer.Serialize(new { scope="header merge only, local diagnostic, not section-10 acceptance",operations=count, bytes_per_operation=allocated,ns_per_operation=ns }));
