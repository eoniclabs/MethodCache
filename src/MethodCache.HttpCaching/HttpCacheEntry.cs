using System.Net;
using System.Net.Http.Headers;

namespace MethodCache.HttpCaching;

/// <summary>
/// Represents a cached HTTP response with metadata for validation and freshness calculation.
/// </summary>
public sealed record HttpCacheEntry
{
    /// <summary>
    /// The URI of the request that generated this cache entry.
    /// </summary>
    public required string RequestUri { get; init; }

    /// <summary>
    /// The HTTP method of the request.
    /// </summary>
    public required string Method { get; init; }

    /// <summary>
    /// The HTTP status code of the response.
    /// </summary>
    public HttpStatusCode StatusCode { get; init; }

    /// <summary>
    /// The response body content.
    /// </summary>
    public byte[] Content { get; init; } = Array.Empty<byte>();

    /// <summary>
    /// The response headers serialized for storage.
    /// </summary>
    public Dictionary<string, string[]> Headers { get; init; } = new();

    /// <summary>
    /// The content headers serialized for storage.
    /// </summary>
    public Dictionary<string, string[]> ContentHeaders { get; init; } = new();

    /// <summary>
    /// The ETag value from the response, if present.
    /// </summary>
    public string? ETag { get; init; }

    /// <summary>
    /// The Last-Modified value from the response, if present.
    /// </summary>
    public DateTimeOffset? LastModified { get; init; }

    /// <summary>
    /// The Cache-Control header parsed from the response.
    /// </summary>
    public CacheControlHeaderValue? CacheControl { get; init; }

    /// <summary>
    /// The Expires header from the response, if present.
    /// </summary>
    public DateTimeOffset? Expires { get; init; }

    /// <summary>
    /// The Date header from the response (when the response was generated by the origin server).
    /// </summary>
    public DateTimeOffset? Date { get; init; }

    /// <summary>
    /// When this entry was stored in the cache.
    /// </summary>
    public DateTimeOffset StoredAt { get; init; }

    /// <summary>
    /// How old the response already was when it was stored: the larger of its <c>Age</c> header and the time
    /// since its <c>Date</c> (RFC 9111 section 4.2.3).
    /// </summary>
    public TimeSpan InitialAge { get; init; }

    /// <summary>
    /// The Vary headers that affect caching for this response. On the entry for a URL whose responses are stored
    /// per variant, the request headers that select the variant.
    /// </summary>
    public string[]? VaryHeaders { get; init; }

    /// <summary>
    /// Set on the entry for a URL whose responses are stored per variant (per <c>Vary</c>, key header or caller).
    /// Variants are found through it, so replacing or removing this entry makes every older variant unreachable.
    /// Storage implementations only need to keep it.
    /// </summary>
    public string? VariantGeneration { get; init; }

    /// <summary>
    /// Creates a cache entry from an HTTP response message, reading at most <paramref name="maxSize"/> bytes of its
    /// body (0 for no limit). Returns <c>null</c> when the body is larger; the response then still holds the whole
    /// body for the caller, streamed rather than buffered.
    /// </summary>
    internal static async Task<HttpCacheEntry?> FromResponseAsync(
        HttpRequestMessage request,
        HttpResponseMessage response,
        DateTimeOffset now,
        long maxSize = 0,
        CancellationToken cancellationToken = default)
    {
        var contentHeaders = SerializeHeaders(response.Content.Headers);
        var body = await response.Content.ReadAsStreamAsync(cancellationToken).ConfigureAwait(false);
        var limit = maxSize > 0 ? maxSize : long.MaxValue;
        var buffer = new MemoryStream();
        var chunk = new byte[81920];
        int read;
        while (buffer.Length <= limit && (read = await body.ReadAsync(chunk, cancellationToken).ConfigureAwait(false)) > 0)
        {
            buffer.Write(chunk, 0, read);
        }

        if (buffer.Length > limit)
        {
            // Too large to cache: hand the caller what was read followed by the rest of the stream
            buffer.Position = 0;
            response.Content = new StreamContent(new ConcatenatedStream(buffer, body));
            RestoreHeaders(response.Content.Headers, contentHeaders);
            return null;
        }

        var content = buffer.ToArray();
        await body.DisposeAsync().ConfigureAwait(false);

        // The body was consumed, so the caller reads it from a copy
        response.Content = new ByteArrayContent(content);
        RestoreHeaders(response.Content.Headers, contentHeaders);

        return new HttpCacheEntry
        {
            RequestUri = request.RequestUri?.ToString() ?? "",
            Method = request.Method.ToString(),
            StatusCode = response.StatusCode,
            Content = content,
            Headers = SerializeHeaders(response.Headers, StorableHeaders(response.Headers)),
            ContentHeaders = contentHeaders,
            ETag = response.Headers.ETag?.Tag,
            LastModified = response.Content.Headers.LastModified,
            CacheControl = response.Headers.CacheControl,
            Expires = response.Content.Headers.Expires,

            // RFC 9110 section 6.6.1: without a Date, the time it was received stands in for it
            Date = response.Headers.Date ?? now,
            StoredAt = now,
            InitialAge = CalculateInitialAge(response, now),
            VaryHeaders = response.Headers.Vary?.ToArray()
        };
    }

    /// <summary>
    /// Converts this cache entry back to an HTTP response message.
    /// </summary>
    internal HttpResponseMessage ToHttpResponse(HttpRequestMessage request)
    {
        var response = new HttpResponseMessage(StatusCode)
        {
            Content = new ByteArrayContent(Content),
            RequestMessage = request
        };

        // Restore response headers
        foreach (var header in Headers)
        {
            response.Headers.TryAddWithoutValidation(header.Key, header.Value);
        }

        // Restore content headers
        foreach (var header in ContentHeaders)
        {
            response.Content.Headers.TryAddWithoutValidation(header.Key, header.Value);
        }

        return response;
    }

    /// <summary>
    /// Updates this entry with new headers from a 304 Not Modified response.
    /// </summary>
    internal HttpCacheEntry WithUpdatedHeaders(HttpResponseMessage notModifiedResponse, DateTimeOffset now)
    {
        var mergedHeaders = new Dictionary<string, string[]>(StringComparer.OrdinalIgnoreCase);

        foreach (var header in Headers)
        {
            mergedHeaders[header.Key] = header.Value;
        }

        var updatedHeaders = SerializeHeaders(notModifiedResponse.Headers, StorableHeaders(notModifiedResponse.Headers));
        foreach (var header in updatedHeaders)
        {
            mergedHeaders[header.Key] = header.Value;
        }

        // RFC 9111 section 3.2: the 304's header fields replace the stored ones, content headers such as Expires
        // included, except those that describe its own (empty) body
        var mergedContentHeaders = new Dictionary<string, string[]>(ContentHeaders, StringComparer.OrdinalIgnoreCase);
        if (notModifiedResponse.Content != null)
        {
            foreach (var header in notModifiedResponse.Content.Headers)
            {
                if (!string.Equals(header.Key, "Content-Length", StringComparison.OrdinalIgnoreCase) &&
                    !string.Equals(header.Key, "Content-Range", StringComparison.OrdinalIgnoreCase))
                {
                    mergedContentHeaders[header.Key] = header.Value.ToArray();
                }
            }
        }

        return this with
        {
            Headers = mergedHeaders,
            ContentHeaders = mergedContentHeaders,
            ETag = notModifiedResponse.Headers.ETag?.Tag ?? ETag,
            LastModified = notModifiedResponse.Content?.Headers.LastModified ?? LastModified,
            CacheControl = notModifiedResponse.Headers.CacheControl ?? CacheControl,
            Expires = notModifiedResponse.Content?.Headers.Expires ?? Expires,
            Date = notModifiedResponse.Headers.Date ?? Date,
            StoredAt = now,
            InitialAge = CalculateInitialAge(notModifiedResponse, now),
            VaryHeaders = notModifiedResponse.Headers.Contains("Vary") ? notModifiedResponse.Headers.Vary.ToArray() : VaryHeaders
        };
    }

    /// <summary>
    /// Determines if this cache entry can be validated with conditional requests.
    /// </summary>
    internal bool CanValidate()
    {
        return !string.IsNullOrEmpty(ETag) || LastModified.HasValue;
    }

    private static TimeSpan CalculateInitialAge(HttpResponseMessage response, DateTimeOffset now)
    {
        var apparentAge = response.Headers.Date is { } date && now > date ? now - date : TimeSpan.Zero;
        var ageValue = response.Headers.Age ?? TimeSpan.Zero;
        return apparentAge > ageValue ? apparentAge : ageValue;
    }

    private static Dictionary<string, string[]> SerializeHeaders(HttpHeaders headers, Func<string, bool>? include = null)
    {
        var result = new Dictionary<string, string[]>();
        foreach (var header in headers)
        {
            if (include == null || include(header.Key))
            {
                result[header.Key] = header.Value.ToArray();
            }
        }
        return result;
    }

    private static void RestoreHeaders(HttpContentHeaders target, Dictionary<string, string[]> headers)
    {
        foreach (var header in headers)
        {
            target.TryAddWithoutValidation(header.Key, header.Value);
        }
    }

    /// <summary>
    /// RFC 9111 section 3.1: hop-by-hop fields describe one connection, not the response, so they are not stored.
    /// <c>Age</c> is recomputed when the entry is served. <c>Set-Cookie</c> is not stored either: it belongs to the
    /// caller the origin answered, and replayed from the cache it would hand that caller's session to others.
    /// </summary>
    private static Func<string, bool> StorableHeaders(HttpResponseHeaders headers)
    {
        var connectionOptions = headers.Connection.ToHashSet(StringComparer.OrdinalIgnoreCase);
        return name => !UnstoredHeaders.Contains(name) && !connectionOptions.Contains(name);
    }

    private static readonly HashSet<string> UnstoredHeaders = new(StringComparer.OrdinalIgnoreCase)
    {
        "Age", "Connection", "Keep-Alive", "Proxy-Connection", "TE", "Trailer", "Transfer-Encoding", "Upgrade",
        "Set-Cookie"
    };

    /// <summary>Reads one stream to its end, then the other.</summary>
    private sealed class ConcatenatedStream(Stream first, Stream second) : Stream
    {
        public override bool CanRead => true;
        public override bool CanSeek => false;
        public override bool CanWrite => false;
        public override long Length => throw new NotSupportedException();
        public override long Position { get => throw new NotSupportedException(); set => throw new NotSupportedException(); }

        public override int Read(byte[] buffer, int offset, int count)
        {
            var read = first.Read(buffer, offset, count);
            return read > 0 ? read : second.Read(buffer, offset, count);
        }

        public override async ValueTask<int> ReadAsync(Memory<byte> buffer, CancellationToken cancellationToken = default)
        {
            var read = await first.ReadAsync(buffer, cancellationToken).ConfigureAwait(false);
            return read > 0 ? read : await second.ReadAsync(buffer, cancellationToken).ConfigureAwait(false);
        }

        public override Task<int> ReadAsync(byte[] buffer, int offset, int count, CancellationToken cancellationToken)
            => ReadAsync(buffer.AsMemory(offset, count), cancellationToken).AsTask();

        public override void Flush()
        {
        }

        public override long Seek(long offset, SeekOrigin origin) => throw new NotSupportedException();
        public override void SetLength(long value) => throw new NotSupportedException();
        public override void Write(byte[] buffer, int offset, int count) => throw new NotSupportedException();

        protected override void Dispose(bool disposing)
        {
            if (disposing)
            {
                first.Dispose();
                second.Dispose();
            }

            base.Dispose(disposing);
        }
    }
}
