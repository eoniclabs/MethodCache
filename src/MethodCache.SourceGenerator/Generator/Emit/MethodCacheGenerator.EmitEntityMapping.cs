#nullable enable

using System;
using System.Linq;
using System.Text;
using System.Threading;
using MethodCache.Internal;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace MethodCache.SourceGenerator
{
    public sealed partial class MethodCacheGenerator
    {
        /// <summary>
        /// Writes the project's MethodCache.EntityFrameworkCore mapping into its assembly, so MC0027 in a project that
        /// references it, such as its tests or a worker, checks writes against the mapped tables instead of counting
        /// every write. Each call is read on its own, so an edit elsewhere regenerates nothing.
        /// </summary>
        private static void RegisterEntityMapping(IncrementalGeneratorInitializationContext context)
        {
            var values = context.SyntaxProvider
                .CreateSyntaxProvider(
                    predicate: static (node, _) => EntityMappingCall.IsCandidate(node),
                    transform: static (ctx, ct) => EntityMappingValue((InvocationExpressionSyntax)ctx.Node, ctx.SemanticModel, ct))
                .Where(static value => value != null)
                .Collect()
                .Select(static (items, _) => new EquatableArray<string>(items.Select(v => v!).Distinct(StringComparer.Ordinal).OrderBy(v => v, StringComparer.Ordinal)))
                .WithTrackingName(TrackingNames.EntityMapping);
            context.RegisterSourceOutput(values, static (ctx, items) => EmitEntityMapping(ctx, items));
        }

        private static string? EntityMappingValue(InvocationExpressionSyntax invocation, SemanticModel model, CancellationToken cancellationToken)
        {
            var options = model.Compilation.GetTypeByMetadataName(EntityMappingCall.OptionsType);
            if (options == null) return null;
            var builder = model.Compilation.GetTypeByMetadataName(EntityMappingCall.BuilderType);
            return EntityMappingCall.Read(invocation, model, options, builder, cancellationToken) is { } call ? EntityMappingMetadata.Write(call) : null;
        }

        private static void EmitEntityMapping(SourceProductionContext context, EquatableArray<string> values)
        {
            // Context and table names alone map no type
            if (!values.Any(v => v.StartsWith("entity:", StringComparison.Ordinal) || v == EntityMappingMetadata.AnyTypeValue)) return;

            var source = new StringBuilder()
                .AppendLine("// <auto-generated/>")
                .AppendLine("// The entity types this project maps for MethodCache.EntityFrameworkCore. MC0027 reads them in the projects that")
                .AppendLine("// reference this one, such as its tests, so a write there is reported only when it changes a mapped table.");
            foreach (var value in values)
            {
                source.Append("[assembly: global::System.Reflection.AssemblyMetadata(")
                    .Append(SymbolDisplay.FormatLiteral(EntityMappingMetadata.Key, quote: true))
                    .Append(", ")
                    .Append(SymbolDisplay.FormatLiteral(value, quote: true))
                    .AppendLine(")]");
            }
            context.AddSource("MethodCacheEntityMapping.g.cs", source.ToString());
        }
    }
}
