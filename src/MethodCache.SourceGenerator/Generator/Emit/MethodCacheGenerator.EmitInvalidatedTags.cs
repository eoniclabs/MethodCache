#nullable enable

using System;
using System.Linq;
using System.Text;
using MethodCache.Internal;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Operations;

namespace MethodCache.SourceGenerator
{
    public sealed partial class MethodCacheGenerator
    {
        /// <summary>
        /// Writes the tags the project invalidates into its assembly: <c>[CacheInvalidate]</c> tags of its interfaces,
        /// and the tags its code passes to InvalidateTagAsync, InvalidateTagsAsync, InvalidateAfterCommit, the
        /// MethodCache.EntityFrameworkCore mapping and its own [InvalidatesCache] helpers. TagCoverage in a test project
        /// reads them from every project the tests reference, so a tag marked InvalidatedElsewhere counts only when
        /// another project invalidates it. Each call is read on its own, so an edit elsewhere regenerates nothing. A test
        /// project writes none: its invalidations test the cache.
        /// </summary>
        private static void RegisterInvalidatedTags(IncrementalGeneratorInitializationContext context)
        {
            var calls = context.SyntaxProvider
                .CreateSyntaxProvider(
                    predicate: static (node, _) => InvalidationTags.IsCandidate(node),
                    transform: static (ctx, ct) => ctx.SemanticModel.GetOperation(ctx.Node, ct) is IInvocationOperation invocation
                        ? Written(InvalidationTags.Of(invocation))
                        : EquatableArray<string>.Empty)
                .Where(static tags => tags.Count > 0)
                .Collect();
            var declared = context.SyntaxProvider
                .ForAttributeWithMetadataName(
                    fullyQualifiedMetadataName: "MethodCache.CacheInvalidateAttribute",
                    predicate: static (node, _) => node.Parent is InterfaceDeclarationSyntax,
                    transform: static (ctx, _) => ctx.TargetSymbol is IMethodSymbol method ? Written(InvalidationTags.CacheInvalidateTags(method)) : EquatableArray<string>.Empty)
                .Where(static tags => tags.Count > 0)
                .Collect();
            var isTestProject = context.CompilationProvider.Select(static (compilation, _) => InvalidationTags.IsTestProject(compilation));
            var values = calls.Combine(declared).Combine(isTestProject)
                .Select(static (input, _) => input.Right
                    ? EquatableArray<string>.Empty
                    : new EquatableArray<string>(input.Left.Left.Concat(input.Left.Right).SelectMany(tags => tags)
                        .Distinct(StringComparer.Ordinal).OrderBy(tag => tag, StringComparer.Ordinal)))
                .WithTrackingName(TrackingNames.InvalidatedTags);
            context.RegisterSourceOutput(values, static (ctx, tags) => EmitInvalidatedTags(ctx, tags));

            static EquatableArray<string> Written(System.Collections.Generic.IReadOnlyList<string>? patterns)
                => patterns is { Count: > 0 } ? new EquatableArray<string>(patterns.Select(InvalidationTags.Write)) : EquatableArray<string>.Empty;
        }

        private static void EmitInvalidatedTags(SourceProductionContext context, EquatableArray<string> tags)
        {
            if (tags.Count == 0) return;

            var source = new StringBuilder()
                .AppendLine("// <auto-generated/>")
                .AppendLine("// The tags this project invalidates, with {} for a placeholder or an interpolated value. TagCoverage in MethodCache.Testing")
                .AppendLine("// reads them in the test projects that reference this one, to check tags marked InvalidatedElsewhere.");
            foreach (var tag in tags)
            {
                source.Append("[assembly: global::System.Reflection.AssemblyMetadata(")
                    .Append(SymbolDisplay.FormatLiteral(InvalidationTags.MetadataKey, quote: true))
                    .Append(", ")
                    .Append(SymbolDisplay.FormatLiteral(tag, quote: true))
                    .AppendLine(")]");
            }
            context.AddSource("MethodCacheInvalidatedTags.g.cs", source.ToString());
        }
    }
}
