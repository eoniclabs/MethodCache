        // ======================== Decorator Emitter ========================
        private static void EmitTagInvalidation(StringBuilder sb, IMethodSymbol method, List<string> staticTags, List<(string template, List<string> paramNames)> dynamicTags, string indent)
        {
            sb.AppendLine($"{indent}var __mcTags = new global::System.Collections.Generic.List<string>();");

            // Add static tags
            if (staticTags.Any())
            {
                // A placeholder that names no parameter stays literal text (MCG009), as it does on cached entries
                var staticTagsWithoutDynamic = staticTags.Where(t => !NamesParameter(method, t)).ToList();
                if (staticTagsWithoutDynamic.Any())
                {
                    sb.Append($"{indent}__mcTags.AddRange(new[] {{ ");
                    sb.Append(string.Join(", ", staticTagsWithoutDynamic.Select(Utils.Literal)));
                    sb.AppendLine(" });");
                }
            }

            // Add dynamic tags
            foreach (var (template, paramNames) in dynamicTags)
            {
                sb.Append($"{indent}__mcTags.Add(string.Format(global::System.Globalization.CultureInfo.InvariantCulture, {Utils.Literal(template)}");
                foreach (var paramName in paramNames)
                {
                    sb.Append($", {FormatTagArgument(method, paramName)}");
                }
                sb.AppendLine("));");
            }
        }

        private static bool NamesParameter(IMethodSymbol method, string tag)
        {
            foreach (System.Text.RegularExpressions.Match match in DynamicTagParameterRegex.Matches(tag))
            {
                if (ResolveTagParameter(method, match.Groups[1].Value) != null)
                {
                    return true;
                }
            }

            return false;
        }

        /// <summary>
        /// The expression that turns an argument into its tag text. Cached entries and invalidation both use it,
        /// so the tags they build always match.
        /// </summary>
        private static string FormatTagArgument(IMethodSymbol method, string paramName)
        {
            // Invariant, so every node and culture builds the same tag text for the same argument
            return $"(global::System.Convert.ToString((object?){Utils.ParameterIdentifier(method.Parameters.Single(p => p.Name == paramName))}, global::System.Globalization.CultureInfo.InvariantCulture) ?? \"null\")";
        }

        private static class DecoratorEmitter
        {
            internal static string Emit(InterfaceInfo info)
            {
                var sb = new StringBuilder();
                var ns = Utils.GetDecoratorNamespace(info.Symbol);
                var interfaceFqn = Utils.GetFullyQualifiedName(info.Symbol);
                var className = Utils.GetDecoratorClassName(info.Symbol);

                static string GetSimpleInterfaceName(INamedTypeSymbol symbol)
                {
                    return symbol.ToDisplayString(new SymbolDisplayFormat(
                        typeQualificationStyle: SymbolDisplayTypeQualificationStyle.NameAndContainingTypesAndNamespaces,
                        genericsOptions: SymbolDisplayGenericsOptions.IncludeTypeParameters));
                }


                // File header
                sb.AppendLine("// <auto-generated/>");
                sb.AppendLine("#nullable enable");
                sb.AppendLine("#pragma warning disable CS8019 // Unnecessary using directive");
                sb.AppendLine("using System;");
                sb.AppendLine("using global::System.Collections.Generic;");
                sb.AppendLine("using global::System.Collections.Concurrent;");
                sb.AppendLine("using global::System.Linq;");
                sb.AppendLine("using global::System.Threading;");
                sb.AppendLine("using global::System.Threading.Tasks;");
                sb.AppendLine("using global::MethodCache;");
                sb.AppendLine("using global::MethodCache.Extensibility;");
                sb.AppendLine("using global::MethodCache.Infrastructure;");
                sb.AppendLine("using global::MethodCache.Policies;");
                sb.AppendLine();
                sb.AppendLine($"namespace {ns}");
                sb.AppendLine("{");

                // Class declaration with generic parameters
                var genericParams = GetClassGenericParameters(info.Symbol);

                // Add XML documentation for generic interface limitations
                if (info.Symbol.IsGenericType)
                {
                    sb.AppendLine("    /// <summary>");
                    sb.AppendLine("    /// Cached implementation of " + GetSimpleInterfaceName(info.Symbol) + ".");
                    sb.AppendLine("    /// </summary>");
                    sb.AppendLine("    /// <remarks>");
                    sb.AppendLine("    /// This generic interface implementation provides type safety and convenience,");
                    sb.AppendLine("    /// but may have slight performance overhead compared to the non-generic interface");
                    sb.AppendLine("    /// for high-throughput scenarios due to runtime type resolution for cache keys.");
                    sb.AppendLine("    /// For maximum performance in critical paths, consider using non-generic interfaces.");
                    sb.AppendLine("    /// </remarks>");
                }

                sb.AppendLine("    [global::System.CodeDom.Compiler.GeneratedCode(\"MethodCacheGenerator\", \"1.0.0\")]");
                sb.AppendLine("    [global::System.Diagnostics.DebuggerNonUserCode]");
                // Internal: generated code in the application's assembly, never part of its public API
                // Disposable only when the interface is: the container keeps every disposable transient it creates.
                // Then both kinds, so disposing the container synchronously still works for an IAsyncDisposable one
                var disposable = info.Symbol.AllInterfaces.Any(i => i.ToDisplayString() is "System.IDisposable" or "System.IAsyncDisposable");
                sb.AppendLine(disposable
                    ? $"    internal sealed class {className}{genericParams} : {interfaceFqn}, global::System.IDisposable, global::System.IAsyncDisposable"
                    : $"    internal sealed class {className}{genericParams} : {interfaceFqn}");

                // Add generic constraints after class declaration
                foreach (var typeParam in Utils.AllTypeParameters(info.Symbol))
                {
                    var constraints = BuildConstraints(typeParam);
                    if (!string.IsNullOrEmpty(constraints))
                    {
                        sb.AppendLine($"        {constraints}");
                    }
                }

                sb.AppendLine("    {");

                // Fields
                sb.AppendLine($"        private readonly {interfaceFqn} _decorated;");
                sb.AppendLine("        private readonly global::MethodCache.ICacheManager _cacheManager;");
                sb.AppendLine("        private readonly global::MethodCache.Extensibility.ICacheKeyGenerator _keyGenerator;");
                sb.AppendLine("        private readonly global::MethodCache.Extensibility.ICacheMetricsProvider? _metricsProvider;");
                sb.AppendLine();

                // Each cached method reads its live policy and key prefix from a CachedMethod shared per registry
                foreach (var cached in info.CachedMethods)
                {
                    sb.AppendLine($"        private readonly global::MethodCache.Infrastructure.CachedMethod _method_{SiteName(cached, info.CachedMethods)};");
                }
                sb.AppendLine();

                // Constructor
                EmitConstructorWithPolicies(sb, className, interfaceFqn, info.Symbol, info.CachedMethods);
                EmitCachedMethodSites(sb, interfaceFqn, info.Symbol, info.CachedMethods);

                // Methods
                var allMethods = info.Symbol.GetMembers()
                    .OfType<IMethodSymbol>()
                    .Concat(info.Symbol.AllInterfaces.SelectMany(i => i.GetMembers().OfType<IMethodSymbol>()))
                    .Distinct(SymbolEqualityComparer.Default)
                    .Cast<IMethodSymbol>()
                    .Where(m => m.MethodKind == MethodKind.Ordinary && Utils.IsInterceptable(m));

                foreach (var method in allMethods)
                {
                    if (method.Parameters.Length == 0 && method.ContainingType.ToDisplayString() is "System.IDisposable" or "System.IAsyncDisposable") continue;
                    var cached = info.CachedMethods.FirstOrDefault(m => SymbolEqualityComparer.Default.Equals(m.Method, method));
                    var invalidate = info.InvalidateMethods.FirstOrDefault(m => SymbolEqualityComparer.Default.Equals(m.Method, method));

                    if (cached != null)
                        EmitCachedMethod(sb, cached, SiteName(cached, info.CachedMethods));
                    else if (invalidate != null)
                        EmitInvalidateMethod(sb, invalidate);
                    else
                        EmitPassthroughMethod(sb, method);
                }

                // The container owns and disposes the implementation, so disposing the decorator does nothing
                if (disposable)
                {
                    sb.AppendLine("        void global::System.IDisposable.Dispose() { }");
                    sb.AppendLine("        global::System.Threading.Tasks.ValueTask global::System.IAsyncDisposable.DisposeAsync() => default;");
                }

                // Properties, indexers and events always call the decorated instance
                var otherMembers = info.Symbol.GetMembers()
                    .Concat(info.Symbol.AllInterfaces.SelectMany(i => i.GetMembers()))
                    .Where(m => !m.IsStatic && m is IPropertySymbol or IEventSymbol)
                    .Where(m => m.IsAbstract || (m.IsVirtual && m.DeclaredAccessibility == Accessibility.Public));
                foreach (var member in otherMembers)
                {
                    if (member is IPropertySymbol property)
                        EmitPassthroughProperty(sb, property);
                    else if (member is IEventSymbol @event)
                        EmitPassthroughEvent(sb, @event);
                }

                sb.AppendLine("    }");
                sb.AppendLine("}");
                sb.AppendLine("#pragma warning restore CS8019");

                return sb.ToString();
            }

            private static string GetClassGenericParameters(INamedTypeSymbol symbol)
            {
                var parameters = Utils.AllTypeParameters(symbol).ToArray();
                return parameters.Length == 0 ? string.Empty
                    : $"<{string.Join(", ", parameters.Select(Utils.TypeParameterIdentifier))}>";
            }

            private static void EmitCachedMethodSites(StringBuilder sb, string interfaceFqn, INamedTypeSymbol interfaceSymbol, System.Collections.Immutable.ImmutableArray<MethodModel> cachedMethods)
            {
                if (cachedMethods.Length == 0)
                {
                    return;
                }

                sb.AppendLine("        private sealed class CachedMethodSites");
                sb.AppendLine("        {");
                foreach (var cached in cachedMethods)
                {
                    sb.AppendLine($"            public readonly global::MethodCache.Infrastructure.CachedMethod {SiteName(cached, cachedMethods)};");
                }
                sb.AppendLine();
                sb.AppendLine("            public CachedMethodSites(global::MethodCache.Policies.IPolicyRegistry registry)");
                sb.AppendLine("            {");
                foreach (var cached in cachedMethods)
                {
                    var methodId = Utils.GetMethodId(cached.Method);
                    var safeFieldName = SiteName(cached, cachedMethods);
                    // Overloads, and names other interfaces in the hierarchy declare too, add their parameter types,
                    // so Find(int) and Find(string) never share keys
                    var keyMethodName = Utils.GetKeyMethodName(cached.Method, interfaceSymbol);

                    // Metrics and spans name the method by its id, such as MyApp.IUserService.GetAsync. A method of a
                    // generic interface, also one inherited from IRepository<User> by IUserRepo, reports the closed
                    // type instead, for example IRepository<User>.Get, so IRepository<Order>.Get is another series
                    var owner = cached.Method.ContainingType.IsGenericType ? cached.Method.ContainingType : interfaceSymbol;
                    var displayName = owner.IsGenericType
                        ? $"{Utils.Literal(owner.Name + "<")} + string.Join(\",\", typeof({Utils.GetFullyQualifiedName(owner)}).GetGenericArguments().Select(t => t.Name)) + {Utils.Literal(">." + Utils.GetMethodName(cached.Method))}"
                        : Utils.Literal(methodId);

                    sb.AppendLine($"                {safeFieldName} = new global::MethodCache.Infrastructure.CachedMethod(global::MethodCache.Infrastructure.PolicyHandle.For(registry, {Utils.Literal(methodId)}), typeof({interfaceFqn}), {Utils.Literal(keyMethodName)}, {displayName});");
                }
                sb.AppendLine("            }");
                sb.AppendLine("        }");
                sb.AppendLine();
            }

            private static void EmitConstructorWithPolicies(StringBuilder sb, string className, string interfaceFqn, INamedTypeSymbol interfaceSymbol, System.Collections.Immutable.ImmutableArray<MethodModel> cachedMethods)
            {
                // Constructor name should NOT include generic parameters - that's invalid C# syntax
                sb.AppendLine($"        public {className}({interfaceFqn} decorated, global::MethodCache.Infrastructure.DecoratorServices services)");
                sb.AppendLine("        {");
                sb.AppendLine("            _decorated = decorated ?? throw new global::System.ArgumentNullException(nameof(decorated));");
                sb.AppendLine("            if (services == null) throw new global::System.ArgumentNullException(nameof(services));");
                sb.AppendLine("            _cacheManager = services.CacheManager;");
                sb.AppendLine("            _keyGenerator = services.KeyGenerator;");
                sb.AppendLine("            _metricsProvider = services.MetricsProvider;");
                if (cachedMethods.Length > 0)
                {
                    sb.AppendLine();
                    sb.AppendLine("            // Created once per container, so a scoped or transient decorator costs only these field copies");
                    sb.AppendLine("            var sites = services.GetSites(static registry => new CachedMethodSites(registry));");
                    foreach (var cached in cachedMethods)
                    {
                        var siteName = SiteName(cached, cachedMethods);
                        sb.AppendLine($"            _method_{siteName} = sites.{siteName};");
                    }
                }
                sb.AppendLine("        }");
                sb.AppendLine();
            }

            /// <summary>
            /// A unique field/site name independent of user member names, including overload suffix look-alikes.
            /// </summary>
            private static string SiteName(MethodModel model, System.Collections.Immutable.ImmutableArray<MethodModel> cachedMethods)
            {
                return "Method" + cachedMethods.IndexOf(model);
            }

            private static void EmitCachedMethod(StringBuilder sb, MethodModel model, string safeFieldName)
            {
                var method = model.Method;

                // Build cache key parameters (exclude CancellationToken)
                var keyParams = ImmutableArrayExtensions.Where(method.Parameters, p => !Utils.IsCancellationToken(p.Type))
                    .ToList();

                ResultKind kind;
                ITypeSymbol valueType;
                if (Utils.IsTask(method.ReturnType, out var taskType))
                {
                    kind = ResultKind.Task;
                    valueType = taskType!;
                }
                else if (Utils.IsValueTask(method.ReturnType, out var valueTaskType))
                {
                    kind = ResultKind.ValueTask;
                    valueType = valueTaskType!;
                }
                else
                {
                    kind = ResultKind.Sync;
                    valueType = method.ReturnType;
                }

                EmitMethodSignature(sb, method);
                sb.AppendLine("        {");

                if (kind == ResultKind.Sync)
                {
                    sb.AppendLine("            // Hits return without blocking. A miss blocks this thread while the value loads; the cache never");
                    sb.AppendLine("            // resumes on the caller's SynchronizationContext, so this can't deadlock. With Redis or SQL Server");
                    sb.AppendLine("            // the wait includes the network read, so prefer async methods on hot paths there.");
                }

                // One read gives the policy and key prefix for this call, even if the policy changes meanwhile
                sb.AppendLine($"            var __mcSnapshot = this._method_{safeFieldName}.Current;");
                var keyStart = sb.Length;

                // Simple arguments, and records or DTOs made of them, are formatted inline; anything else goes
                // through the key generator.
                var rawKeyParam = GetRawKeyParameter(keyParams);
                var stackKeyLookup = false;
                if (rawKeyParam != null)
                {
                    EmitRawKey(sb, rawKeyParam, "            ");
                }
                else if (keyParams.Count > 0 && keyParams.All(p => IsSimpleType(p.Type)))
                {
                    EmitStackKeyLookup(sb, keyParams, kind, valueType, safeFieldName);
                    stackKeyLookup = true;
                }
                else if (TryBuildInlineKey(keyParams, out var inlineKey, out var exactTypeChecks))
                {
                    if (exactTypeChecks.Count == 0)
                    {
                        sb.AppendLine($"            var __mcKey = {inlineKey};");
                    }
                    else
                    {
                        // A subclass can carry state the declared type doesn't have, so it goes through the key generator
                        sb.AppendLine($"            var __mcKey = {string.Join(" && ", exactTypeChecks)}");
                        sb.AppendLine($"                ? {inlineKey}");
                        sb.AppendLine($"                : {GeneratedKeyExpression(safeFieldName, keyParams)};");
                    }
                }
                else
                {
                    EmitGeneratedKey(sb, safeFieldName, keyParams);
                }

                if (!stackKeyLookup)
                {
                    sb.AppendLine();
                    EmitHit(sb, kind, valueType, safeFieldName, "__mcKey");
                }

                if (method.IsGenericMethod)
                {
                    // The type arguments are part of the key, so Get<int>(1) and Get<string>(1) never share an entry
                    var typeArguments = string.Join(", \",\", ", method.TypeParameters.Select(tp => $"typeof({Utils.TypeParameterIdentifier(tp)}).ToString()"));
                    var declarations = $"            var __mcTypeArguments = string.Concat(\"<\", {typeArguments}, \">\");\n" +
                                       "            var __mcPrefix = string.Concat(__mcSnapshot.KeyPrefix, __mcTypeArguments);\n";
                    // The key code was emitted with the plain prefix; point it at the one with the type arguments
                    sb.Replace("__mcSnapshot.KeyPrefix", "__mcPrefix", keyStart, sb.Length - keyStart);
                    sb.Insert(keyStart, declarations);
                    sb.Replace($"this._method_{safeFieldName}.KeyMethod", $"string.Concat(this._method_{safeFieldName}.KeyMethod, __mcTypeArguments)", keyStart, sb.Length - keyStart);
                }

                EmitMiss(sb, method, kind, valueType, safeFieldName, GetTagParameters(method));

                sb.AppendLine("        }");
                sb.AppendLine();
                EmitLoader(sb, method, kind, valueType, safeFieldName);
            }

            private enum ResultKind
            {
                Task,
                ValueTask,
                Sync
            }

            /// <summary>
            /// Emits the key and the hit lookup for methods whose arguments are all simple values. On .NET 9 and later
            /// the key is written into a stack buffer and looked up as a span, so a hit allocates no key string; the
            /// string is only made on a miss. Older frameworks have no allocation-free dictionary lookup, so they keep
            /// the string key.
            /// </summary>
            private static void EmitStackKeyLookup(StringBuilder sb, List<IParameterSymbol> keyParams, ResultKind kind, ITypeSymbol valueType, string safeFieldName)
            {
                TryBuildInlineKey(keyParams, out var stringKey, out _);

                sb.AppendLine("#if NET9_0_OR_GREATER");
                sb.AppendLine("            var __mcKeyBuilder = new global::MethodCache.Infrastructure.MethodCacheKeyBuilder(stackalloc char[global::MethodCache.Infrastructure.MethodCacheKeyBuilder.StackBufferSize]);");
                sb.AppendLine("            __mcKeyBuilder.Append(__mcSnapshot.KeyPrefix);");
                foreach (var param in keyParams)
                {
                    sb.AppendLine(AppendSimpleValue(Utils.ParameterIdentifier(param), param.Type));
                }

                sb.AppendLine();
                EmitHit(sb, kind, valueType, safeFieldName, "__mcKeyBuilder.AsSpan()");
                sb.AppendLine("            var __mcKey = __mcKeyBuilder.ToString();");
                sb.AppendLine("#else");
                sb.AppendLine($"            var __mcKey = {stringKey};");
                sb.AppendLine();
                EmitHit(sb, kind, valueType, safeFieldName, "__mcKey");
                sb.AppendLine("#endif");
            }

            private static List<string> GetTagParameters(IMethodSymbol method)
                => method.Parameters.Select(parameter => parameter.Name).ToList();

            /// <summary>
            /// Emits the lookup shared by every cached method: one synchronous probe whose result says whether an
            /// entry exists (so null, 0 and false are hits too).
            /// </summary>
            private static void EmitHit(StringBuilder sb, ResultKind kind, ITypeSymbol valueType, string safeFieldName, string key)
            {
                var type = Utils.GetReturnTypeForSignature(valueType);

                // Task methods get the entry's completed task back, so a hit does not allocate a new Task
                sb.AppendLine(kind == ResultKind.Task
                    ? $"            if (this._cacheManager.TryGetFastTask<{type}>({key}, out var __mcCachedTask))"
                    : $"            if (this._cacheManager.TryGetFast<{type}>({key}, out var __mcCachedValue))");
                sb.AppendLine("            {");
                sb.AppendLine($"                this._metricsProvider?.CacheHit(this._method_{safeFieldName}.Name);");
                switch (kind)
                {
                    case ResultKind.Task:
                        sb.AppendLine("                return __mcCachedTask;");
                        break;
                    case ResultKind.ValueTask:
                        sb.AppendLine($"                return new global::System.Threading.Tasks.ValueTask<{type}>(__mcCachedValue!);");
                        break;
                    default:
                        sb.AppendLine("                return __mcCachedValue!;");
                        break;
                }

                sb.AppendLine("            }");
                sb.AppendLine();
            }

            /// <summary>Emits the cache manager's loading path for a miss.</summary>
            private static void EmitMiss(StringBuilder sb, IMethodSymbol method, ResultKind kind, ITypeSymbol valueType, string safeFieldName, List<string> tagParameters)
            {
                var type = Utils.GetReturnTypeForSignature(valueType);
                sb.AppendLine("            // Miss: the cache manager records the hit or miss (another caller may have loaded it meanwhile)");

                var policy = "__mcSnapshot.Policy";
                if (tagParameters.Count > 0)
                {
                    // Tags such as "user:{userId}" get this call's arguments, matching what [CacheInvalidate] removes
                    var names = string.Join(", ", tagParameters.Select(p => $"\"{p}\""));
                    var values = string.Join(", ", tagParameters.Select(p => FormatTagArgument(method, p)));
                    sb.AppendLine($"            var __mcPolicy = {policy};");
                    sb.AppendLine("            if (__mcPolicy.Tags.Count > 0)");
                    sb.AppendLine($"                __mcPolicy = global::MethodCache.Infrastructure.CacheTagTemplates.Expand(__mcPolicy, new[] {{ {names} }}, new[] {{ {values} }});");
                    policy = "__mcPolicy";
                }

                // The key code may have tested reference arguments for null; they are passed on unchanged
                var arguments = string.Concat(method.Parameters.Select(p => ", " + Utils.ParameterIdentifier(p) + (p.Type.IsValueType ? "" : "!")));
                var load = $"{LoaderName(method, safeFieldName)}(__mcKey, {policy}{arguments})";

                switch (kind)
                {
                    case ResultKind.Task:
                        sb.AppendLine($"            return {load};");
                        break;
                    case ResultKind.ValueTask:
                        sb.AppendLine($"            return new global::System.Threading.Tasks.ValueTask<{type}>({load});");
                        break;
                    default:
                        sb.AppendLine($"            return {load}.ConfigureAwait(false).GetAwaiter().GetResult();");
                        break;
                }
            }

            private static string LoaderName(IMethodSymbol method, string safeFieldName)
            {
                var typeArgs = method.TypeParameters.Any()
                    ? $"<{string.Join(", ", method.TypeParameters.Select(tp => Utils.TypeParameterIdentifier(tp)))}>"
                    : string.Empty;
                return $"__Load_{safeFieldName}{typeArgs}";
            }

            /// <summary>
            /// Emits the miss path as its own method. The factory lambda captures the arguments; in the cached method
            /// itself the compiler would allocate that closure on entry, so every hit would pay for it. Its own
            /// parameters are prefixed so they can't clash with the method's parameter names.
            /// </summary>
            private static void EmitLoader(StringBuilder sb, IMethodSymbol method, ResultKind kind, ITypeSymbol valueType, string safeFieldName)
            {
                var type = Utils.GetReturnTypeForSignature(valueType);
                var parameters = string.Concat(method.Parameters.Select(p => $", {Utils.GetReturnTypeForSignature(p.Type)} {Utils.ParameterIdentifier(p)}"));
                // A refresh-ahead or fail-safe load that outlives its caller gets a scoped or transient service
                // from its own scope (DecoratorServices.ForLoad); otherwise this is the decorated instance
                var call = BuildMethodCall(method, $"global::MethodCache.Infrastructure.DecoratorServices.ForLoad(this._method_{safeFieldName}, this._decorated)");

                // The decorated method's own task is the factory, so a miss doesn't add an async state machine
                var factory = kind switch
                {
                    ResultKind.Task => $"() => {call}!",
                    ResultKind.ValueTask => $"() => {call}.AsTask()!",
                    _ => $"() => global::System.Threading.Tasks.Task.FromResult({call})!"
                };

                sb.AppendLine($"        private global::System.Threading.Tasks.Task<{type}> {LoaderName(method, safeFieldName)}(string __cacheKey, global::MethodCache.Infrastructure.CacheRuntimePolicy __policy{parameters})");
                foreach (var tp in method.TypeParameters)
                {
                    var constraints = BuildConstraints(tp);
                    if (!string.IsNullOrEmpty(constraints))
                    {
                        sb.AppendLine($"            {constraints}");
                    }
                }

                // The method's own token lets the cache tell a caller giving up from a failing dependency
                var token = method.Parameters.FirstOrDefault(p => Utils.IsCancellationToken(p.Type));
                var tokenArgument = token != null ? ", " + Utils.ParameterIdentifier(token) : string.Empty;
                sb.AppendLine($"            => this._cacheManager.GetOrCreateFastAsync<{type}>(__cacheKey, this._method_{safeFieldName}.Name, {factory}, __policy{tokenArgument});");
                sb.AppendLine();
            }

            /// <summary>
            /// Builds the key expression for methods whose arguments can all be formatted without the key generator:
            /// simple values, <c>ICacheKeyProvider</c> types, and records, DTOs or structs whose public members are
            /// simple values. <paramref name="exactTypeChecks"/> lists the conditions under which the expression is
            /// valid; when one fails at runtime, the caller uses the key generator instead.
            /// </summary>
            private static bool TryBuildInlineKey(List<IParameterSymbol> keyParams, out string expression, out List<string> exactTypeChecks)
            {
                expression = "__mcSnapshot.KeyPrefix";
                exactTypeChecks = new List<string>();
                if (keyParams.Count == 0)
                {
                    return true;
                }

                var pieces = new List<string> { "__mcSnapshot.KeyPrefix" };
                foreach (var param in keyParams)
                {
                    pieces.Add("global::MethodCache.MethodCacheKeys.Separator");
                    var name = Utils.ParameterIdentifier(param);
                    if (IsSimpleType(param.Type))
                    {
                        pieces.Add(FormatSimpleValue(name, param.Type));
                    }
                    else if (ImplementsCacheKeyProvider(param.Type))
                    {
                        // Through the interface, so explicit and re-implemented CacheKeyPart members are the ones called
                        var keyPart = $"global::MethodCache.MethodCacheKeys.Part(((global::MethodCache.ICacheKeyProvider){name}).CacheKeyPart)";
                        pieces.Add(param.Type.IsValueType
                            ? keyPart
                            : $"({name} is null ? global::MethodCache.MethodCacheKeys.Null : {keyPart})");
                    }
                    else if (TryGetKeyMembers(param.Type, out var members))
                    {
                        AddObjectPieces(pieces, name, param.Type, members);
                        if (param.Type.TypeKind == TypeKind.Class && !param.Type.IsSealed)
                        {
                            exactTypeChecks.Add($"({name} is null || {name}.GetType() == typeof({Utils.GetFullyQualifiedName(param.Type)}))");
                        }
                    }
                    else if (TryFormatSequence(name, param.Type, out var sequence))
                    {
                        if (IsExactType(param.Type))
                        {
                            pieces.Add(sequence);
                        }
                        else
                        {
                            // Another runtime type than the declared one (an array and a list behind IEnumerable<T>, a
                            // subclass of List<T>) is written before the elements, so equal elements in two collection
                            // types stay two arguments. A type name never starts like a sequence or null does.
                            var typed = $"string.Concat(global::MethodCache.MethodCacheKeys.Part({name}.GetType().ToString()), global::MethodCache.MethodCacheKeys.Separator, {sequence})";
                            pieces.Add(param.Type is IArrayTypeSymbol || (param.Type.TypeKind == TypeKind.Class && !param.Type.IsAbstract)
                                ? $"({name} is null || {name}.GetType() == typeof({Utils.GetFullyQualifiedName(param.Type)}) ? {sequence} : {typed})"
                                : $"({name} is null ? global::MethodCache.MethodCacheKeys.Null : {typed})");
                        }
                    }
                    else
                    {
                        exactTypeChecks.Clear();
                        return false;
                    }
                }

                expression = $"string.Concat({string.Join(", ", pieces)})";
                return true;
            }

            /// <summary>
            /// Formats an array or collection whose elements the decorator can write itself: simple values,
            /// <c>ICacheKeyProvider</c> types, and sealed records, classes or structs made of simple values (an unsealed
            /// element type could hold a subclass with more state). The element type comes from the collection's one
            /// <c>IEnumerable&lt;T&gt;</c>, so the element lambda is inferred and its nullability follows the argument's.
            /// </summary>
            private static bool TryFormatSequence(string name, ITypeSymbol type, out string expression)
            {
                expression = string.Empty;
                var element = GetSequenceElementType(type);
                if (element == null)
                {
                    return false;
                }

                const string item = "__mcItem";
                string part;
                if (IsSimpleType(element))
                {
                    part = FormatSimpleValue(item, element);
                }
                else if (ImplementsCacheKeyProvider(element))
                {
                    var keyPart = $"global::MethodCache.MethodCacheKeys.Part(((global::MethodCache.ICacheKeyProvider){item}).CacheKeyPart)";
                    part = element.IsValueType ? keyPart : $"({item} is null ? global::MethodCache.MethodCacheKeys.Null : {keyPart})";
                }
                else if ((element.IsValueType || element.IsSealed) && TryGetKeyMembers(element, out var members))
                {
                    var pieces = new List<string>();
                    AddObjectPieces(pieces, item, element, members);
                    part = pieces.Count == 1 ? pieces[0] : $"string.Concat({string.Join(", ", pieces)})";
                }
                else
                {
                    return false;
                }

                expression = $"global::MethodCache.MethodCacheKeys.Sequence({name}, static {item} => {part})";
                return true;
            }

            /// <summary>
            /// True when every value declared as <paramref name="type"/> has exactly that runtime type: value types,
            /// sealed classes, and arrays of such elements (a <c>Shape[]</c> can hold a <c>Circle[]</c>).
            /// </summary>
            private static bool IsExactType(ITypeSymbol type)
                => type is IArrayTypeSymbol array
                    ? IsExactType(array.ElementType)
                    : type.IsValueType || type.IsSealed;

            /// <summary>
            /// The element type of a one-dimensional array, or of a type that is or implements exactly one
            /// <c>IEnumerable&lt;T&gt;</c>; null for anything else.
            /// </summary>
            internal static ITypeSymbol? GetSequenceElementType(ITypeSymbol type)
            {
                if (type is IArrayTypeSymbol array)
                {
                    return array.Rank == 1 ? array.ElementType : null;
                }

                if (type is not INamedTypeSymbol named || type.SpecialType == SpecialType.System_String)
                {
                    return null;
                }

                if (named.ConstructedFrom.SpecialType == SpecialType.System_Collections_Generic_IEnumerable_T)
                {
                    return named.TypeArguments[0];
                }

                var enumerables = named.AllInterfaces
                    .Where(i => i.ConstructedFrom.SpecialType == SpecialType.System_Collections_Generic_IEnumerable_T)
                    .ToList();
                return enumerables.Count == 1 ? enumerables[0].TypeArguments[0] : null;
            }

            /// <summary>
            /// Writes an object as <c>(member1:member2:...)</c> and <c>null</c> as <c>\0</c>. The opening parenthesis
            /// keeps a non-null object apart from <c>null</c> even when its first member is <c>null</c>, and the member
            /// count is fixed by the type, so no two argument lists share a key.
            /// </summary>
            private static void AddObjectPieces(List<string> pieces, string name, ITypeSymbol type, List<(string Name, ITypeSymbol Type)> members)
            {
                var memberPieces = new List<string>();
                foreach (var member in members)
                {
                    if (memberPieces.Count > 0)
                    {
                        memberPieces.Add("global::MethodCache.MethodCacheKeys.Separator");
                    }

                    memberPieces.Add(FormatSimpleValue($"{name}.@{member.Name}", member.Type));
                }

                if (type.IsValueType)
                {
                    pieces.Add("\"(\"");
                    pieces.AddRange(memberPieces);
                    pieces.Add("\")\"");
                    return;
                }

                pieces.Add($"({name} is null ? global::MethodCache.MethodCacheKeys.Null : string.Concat(\"(\", {string.Join(", ", memberPieces)}, \")\"))");
            }

            private static string FormatSimpleValue(string expression, ITypeSymbol type)
            {
                if (type is INamedTypeSymbol { ConstructedFrom.SpecialType: SpecialType.System_Nullable_T })
                {
                    return $"({expression}.HasValue ? global::MethodCache.MethodCacheKeys.Part({expression}.Value) : global::MethodCache.MethodCacheKeys.Null)";
                }

                return $"global::MethodCache.MethodCacheKeys.Part({expression})";
            }

            private static string AppendSimpleValue(string expression, ITypeSymbol type)
            {
                if (type is INamedTypeSymbol { ConstructedFrom.SpecialType: SpecialType.System_Nullable_T })
                {
                    return $"            if ({expression}.HasValue) __mcKeyBuilder.AppendPart({expression}.Value); else __mcKeyBuilder.AppendNullPart();";
                }

                return $"            __mcKeyBuilder.AppendPart({expression});";
            }

            /// <summary>
            /// A class or struct that implements <c>ICacheKeyProvider</c>, or that interface or one derived from it.
            /// </summary>
            internal static bool ImplementsCacheKeyProvider(ITypeSymbol type)
                => type.TypeKind switch
                {
                    TypeKind.Class or TypeKind.Struct => type.AllInterfaces.Any(IsCacheKeyProvider),
                    TypeKind.Interface => IsCacheKeyProvider(type) || type.AllInterfaces.Any(IsCacheKeyProvider),
                    _ => false,
                };

            private static bool IsCacheKeyProvider(ITypeSymbol type)
                => type is { Name: "ICacheKeyProvider", ContainingNamespace: { Name: "MethodCache", ContainingNamespace.IsGlobalNamespace: true } };

            /// <summary>
            /// Collects the public instance properties and fields of a concrete class or struct, the same members
            /// MessagePack's contractless serializer would write, when every one of them is a simple value.
            /// </summary>
            private static bool TryGetKeyMembers(ITypeSymbol type, out List<(string Name, ITypeSymbol Type)> members)
            {
                members = new List<(string Name, ITypeSymbol Type)>();
                if (type is not INamedTypeSymbol named ||
                    named.TypeKind is not (TypeKind.Class or TypeKind.Struct) ||
                    named.IsAbstract ||
                    named.SpecialType != SpecialType.None ||
                    (IsFrameworkType(named) && !FrameworkComposites.Contains(MetadataName(named.OriginalDefinition))) ||
                    named.AllInterfaces.Any(i => i.SpecialType == SpecialType.System_Collections_IEnumerable))
                {
                    return false;
                }

                var seen = new HashSet<string>(StringComparer.Ordinal);
                for (var current = named; current is not null && current.SpecialType is not (SpecialType.System_Object or SpecialType.System_ValueType); current = current.BaseType)
                {
                    foreach (var member in current.GetMembers())
                    {
                        if (member.IsStatic || member.DeclaredAccessibility != Accessibility.Public || member.IsImplicitlyDeclared || !seen.Add(member.Name))
                        {
                            continue;
                        }

                        ITypeSymbol memberType;
                        switch (member)
                        {
                            case IPropertySymbol { IsIndexer: false, GetMethod.DeclaredAccessibility: Accessibility.Public } property:
                                memberType = property.Type;
                                break;
                            case IFieldSymbol field:
                                memberType = field.Type;
                                break;
                            default:
                                continue;
                        }

                        if (member.GetAttributes().Any(a => a.AttributeClass?.Name is "IgnoreDataMemberAttribute" or "IgnoreMemberAttribute"))
                        {
                            continue;
                        }

                        if (!IsSimpleType(memberType))
                        {
                            members.Clear();
                            return false;
                        }

                        members.Add((member.Name, memberType));
                    }
                }

                return members.Count > 0;
            }

            private static bool IsSimpleType(ITypeSymbol type)
            {
                if (type.TypeKind == TypeKind.Enum)
                {
                    return true;
                }

                if (type is INamedTypeSymbol { ConstructedFrom.SpecialType: SpecialType.System_Nullable_T } nullable)
                {
                    return IsSimpleType(nullable.TypeArguments[0]);
                }

                switch (type.SpecialType)
                {
                    case SpecialType.System_String:
                    case SpecialType.System_Boolean:
                    case SpecialType.System_Byte:
                    case SpecialType.System_SByte:
                    case SpecialType.System_Int16:
                    case SpecialType.System_UInt16:
                    case SpecialType.System_Int32:
                    case SpecialType.System_UInt32:
                    case SpecialType.System_Int64:
                    case SpecialType.System_UInt64:
                    case SpecialType.System_Single:
                    case SpecialType.System_Double:
                    case SpecialType.System_Decimal:
                    case SpecialType.System_DateTime:
                        return true;
                }

                // Guid and DateTimeOffset have no SpecialType; MethodCacheKeys.Part formats both
                return type.ContainingNamespace?.ToDisplayString() == "System" &&
                       type.Name is "Guid" or "DateTimeOffset";
            }

            private static string GetRawKeyExpression(IParameterSymbol param)
            {
                var name = Utils.ParameterIdentifier(param);
                if (param.Type.SpecialType == SpecialType.System_String)
                {
                    return $"{name} ?? \"null\"";
                }

                // Invariant, so 1.5 is "1.5" and -1 is "-1" on every machine, whatever its culture
                const string invariant = "global::System.Globalization.CultureInfo.InvariantCulture";
                if (param.Type is INamedTypeSymbol { ConstructedFrom.SpecialType: SpecialType.System_Nullable_T } nullable)
                {
                    var underlying = nullable.TypeArguments[0];
                    return underlying.TypeKind == TypeKind.Enum
                        ? $"({name} is null ? \"null\" : {GetRawEnumExpression($"{name}.Value")})"
                        : IsDateTime(underlying)
                            ? $"({name} is null ? \"null\" : global::MethodCache.MethodCacheKeys.Part({name}.Value))"
                            : $"({name} is null ? \"null\" : global::System.Convert.ToString((object){name}, {invariant}) ?? \"null\")";
                }

                if (param.Type.TypeKind == TypeKind.Enum)
                {
                    return GetRawEnumExpression(name);
                }

                // As in generated keys: fractions of a second and the offset are kept, and a local time is written as
                // UTC, so the key doesn't depend on the server's time zone
                if (IsDateTime(param.Type))
                {
                    return $"global::MethodCache.MethodCacheKeys.Part({name})";
                }

                if (param.Type.IsValueType)
                {
                    if (!IsFormattable(param.Type))
                    {
                        return $"{name}.ToString()";
                    }

                    // A struct that implements IFormattable explicitly has no public ToString(format, provider)
                    return HasPublicFormattableToString(param.Type)
                        ? $"{name}.ToString(null, {invariant})"
                        : $"((global::System.IFormattable){name}).ToString(null, {invariant})";
                }

                return $"({name} is null ? \"null\" : global::System.Convert.ToString((object){name}, {invariant}) ?? \"null\")";
            }

            /// <summary>
            /// A named enum value keeps its name; a value without one is written as its number in the invariant culture,
            /// since the enum's own formatting would write a negative number with the culture's minus sign.
            /// </summary>
            private static string GetRawEnumExpression(string value)
                => $"({value}.ToString() is var __rawEnumName && (char.IsLetter(__rawEnumName[0]) || __rawEnumName[0] == '_') ? __rawEnumName : global::MethodCache.MethodCacheKeys.Part({value}))";

            private static bool IsDateTime(ITypeSymbol type)
                => type.SpecialType == SpecialType.System_DateTime ||
                   type is { Name: "DateTimeOffset", ContainingNamespace: { Name: "System", ContainingNamespace.IsGlobalNamespace: true } };

            private static bool IsFormattable(ITypeSymbol type)
                => type.AllInterfaces.Any(i => i.ToDisplayString() == "System.IFormattable");

            private static bool HasPublicFormattableToString(ITypeSymbol type)
                => type.GetMembers("ToString").OfType<IMethodSymbol>().Any(m =>
                    m.DeclaredAccessibility == Accessibility.Public && !m.IsStatic && m.Parameters.Length == 2 &&
                    m.Parameters[0].Type.SpecialType == SpecialType.System_String &&
                    m.Parameters[1].Type.ToDisplayString() == "System.IFormatProvider");

            internal static IParameterSymbol? GetRawKeyParameter(IEnumerable<IParameterSymbol> keyParams)
            {
                foreach (var param in keyParams)
                {
                    foreach (var attribute in param.GetAttributes())
                    {
                        if (IsRawKeyAttribute(attribute))
                        {
                            return param;
                        }
                    }
                }

                return null;
            }

            private static bool IsRawKeyAttribute(AttributeData attribute)
            {
                if (!string.Equals(attribute.AttributeClass?.ToDisplayString(), "MethodCache.CacheKeyAttribute", StringComparison.Ordinal))
                {
                    return false;
                }

                foreach (var namedArgument in attribute.NamedArguments)
                {
                    if (namedArgument.Key == "UseAsRawKey" && namedArgument.Value.Value is bool flag && flag)
                    {
                        return true;
                    }
                }

                return false;
            }

            private static void EmitRawKey(StringBuilder sb, IParameterSymbol rawKeyParam, string indent)
            {
                sb.AppendLine($"{indent}// Raw key optimization: [CacheKey(UseAsRawKey = true)] detected");
                sb.AppendLine($"{indent}var __mcKey = {GetRawKeyExpression(rawKeyParam)};");
            }

            private static void EmitGeneratedKey(StringBuilder sb, string safeFieldName, List<IParameterSymbol> keyParams)
            {
                if (keyParams.Count == 0)
                {
                    sb.AppendLine("            var __mcKey = __mcSnapshot.KeyPrefix;");
                    return;
                }

                // Arguments that have no inline key format go through the registered key generator,
                // which keeps the service and method prefix so keys stay recognizable.
                sb.AppendLine($"            var __mcKey = {GeneratedKeyExpression(safeFieldName, keyParams)};");
            }

            private static string GeneratedKeyExpression(string safeFieldName, List<IParameterSymbol> keyParams)
                => $"this._keyGenerator.GenerateKey(this._method_{safeFieldName}.KeyMethod, new object?[] {{ {string.Join(", ", keyParams.Select(p => Utils.ParameterIdentifier(p)))} }}, __mcSnapshot.Policy)";

            private static void EmitInvalidateMethod(StringBuilder sb, MethodModel model)
            {
                var method = model.Method;
                var tags = ExtractTags(model.InvalidateAttr!);
                var dynamicTags = ParseDynamicTags(tags, method);

                var awaitable = Utils.IsTask(method.ReturnType, out _) || Utils.IsValueTask(method.ReturnType, out _);
                var byRefReturn = method.ReturnsByRef || method.ReturnsByRefReadonly;
                var deferredWrapper = awaitable && !byRefReturn && method.Parameters.Any(p => p.RefKind != RefKind.None || IsRefLikeType(p.Type));
                EmitMethodSignature(sb, method, awaitable && !byRefReturn && !deferredWrapper ? "async " : string.Empty);
                sb.AppendLine("        {");
                var call = BuildMethodCall(method);
                if (deferredWrapper)
                    EmitDeferredInvalidateMethodBody(sb, method, call, tags, dynamicTags);
                else if (awaitable && !byRefReturn)
                    EmitAsyncInvalidateMethodBody(sb, method, call, tags, dynamicTags);
                else
                    EmitSyncInvalidateMethodBody(sb, method, call, tags, dynamicTags);

                sb.AppendLine("        }");
                sb.AppendLine();
            }

            // The original call and by-reference arguments must stay in a non-async method. Only its
            // returned operation and the tags captured after that call cross the asynchronous boundary.
            private static void EmitDeferredInvalidateMethodBody(StringBuilder sb, IMethodSymbol method, string call, List<string> staticTags, List<(string template, List<string> paramNames)> dynamicTags)
            {
                if (staticTags.Count == 0 && dynamicTags.Count == 0)
                {
                    sb.AppendLine($"            return {call};");
                    return;
                }

                var returnType = Utils.GetReturnTypeForSignature(method.ReturnType);
                var hasResult = (Utils.IsTask(method.ReturnType, out var resultType) || Utils.IsValueTask(method.ReturnType, out resultType)) && resultType != null;
                sb.AppendLine($"            var __mcPending = {call};");
                EmitTagInvalidation(sb, method, staticTags, dynamicTags, "            ");
                sb.AppendLine("            return __mcComplete(__mcPending, __mcTags.ToArray());");
                sb.AppendLine($"            async {returnType} __mcComplete({returnType} __mcOperation, string[] __mcCapturedTags)");
                sb.AppendLine("            {");
                sb.AppendLine(hasResult
                    ? "                var __mcResult = await __mcOperation.ConfigureAwait(false);"
                    : "                await __mcOperation.ConfigureAwait(false);");
                sb.AppendLine("                await this._cacheManager.InvalidateByTagsAsync(__mcCapturedTags).ConfigureAwait(false);");
                if (hasResult)
                    sb.AppendLine("                return __mcResult;");
                sb.AppendLine("            }");
            }

            private static void EmitAsyncInvalidateMethodBody(StringBuilder sb, IMethodSymbol method, string call, List<string> staticTags, List<(string template, List<string> paramNames)> dynamicTags)
            {
                sb.AppendLine("            try");
                sb.AppendLine("            {");

                // Task and ValueTask have no result to return
                var hasResult = (Utils.IsTask(method.ReturnType, out var resultType) || Utils.IsValueTask(method.ReturnType, out resultType)) && resultType != null;
                if (!hasResult)
                {
                    sb.AppendLine($"                await {call}.ConfigureAwait(false);");
                }
                else
                {
                    sb.AppendLine($"                var __mcResult = await {call}.ConfigureAwait(false);");
                }

                // Invalidate cache AFTER successful execution
                if (staticTags.Any() || dynamicTags.Any())
                {
                    EmitTagInvalidation(sb, method, staticTags, dynamicTags, "                ");
                    sb.AppendLine("                await this._cacheManager.InvalidateByTagsAsync(__mcTags.ToArray()).ConfigureAwait(false);");
                }

                if (hasResult)
                {
                    sb.AppendLine("                return __mcResult;");
                }

                sb.AppendLine("            }");
                sb.AppendLine("            catch");
                sb.AppendLine("            {");
                sb.AppendLine("                // Don't invalidate cache on failure");
                sb.AppendLine("                throw;");
                sb.AppendLine("            }");
            }

            private static void EmitSyncInvalidateMethodBody(StringBuilder sb, IMethodSymbol method, string call, List<string> staticTags, List<(string template, List<string> paramNames)> dynamicTags)
            {
                sb.AppendLine("            try");
                sb.AppendLine("            {");

                if (method.ReturnsVoid)
                {
                    sb.AppendLine($"                {call};");
                }
                else
                {
                    var reference = method.ReturnsByRefReadonly ? "ref readonly " : method.ReturnsByRef ? "ref " : string.Empty;
                    var initializer = reference.Length > 0 ? "ref " : string.Empty;
                    sb.AppendLine($"                {reference}var __mcResult = {initializer}{call};");
                }

                // Invalidate cache AFTER successful execution
                if (staticTags.Any() || dynamicTags.Any())
                {
                    EmitTagInvalidation(sb, method, staticTags, dynamicTags, "                ");
                    sb.AppendLine("                this._cacheManager.InvalidateByTagsAsync(__mcTags.ToArray()).GetAwaiter().GetResult();");
                }

                if (!method.ReturnsVoid)
                {
                    sb.AppendLine(method.ReturnsByRef || method.ReturnsByRefReadonly ? "                return ref __mcResult;" : "                return __mcResult;");
                }

                sb.AppendLine("            }");
                sb.AppendLine("            catch");
                sb.AppendLine("            {");
                sb.AppendLine("                // Don't invalidate cache on failure");
                sb.AppendLine("                throw;");
                sb.AppendLine("            }");
            }

            private static void EmitPassthroughMethod(StringBuilder sb, IMethodSymbol method)
            {
                EmitMethodSignature(sb, method);
                sb.AppendLine("        {");

                var call = BuildMethodCall(method);
                if (method.ReturnsVoid)
                    sb.AppendLine($"            {call};");
                else if (method.ReturnsByRef || method.ReturnsByRefReadonly)
                    sb.AppendLine($"            return ref {call};");
                else
                    sb.AppendLine($"            return {call};");

                sb.AppendLine("        }");
                sb.AppendLine();
            }


            private static void EmitPassthroughProperty(StringBuilder sb, IPropertySymbol property)
            {
                // Explicit implementation, so a property declared by a base interface or hidden by a derived one
                // still reaches the matching member of the decorated instance
                var declaring = Utils.GetReturnTypeForSignature(property.ContainingType);
                var target = $"(({declaring})this._decorated)";
                var byRef = property.ReturnsByRefReadonly ? "ref readonly " : property.ReturnsByRef ? "ref " : string.Empty;
                var type = Utils.GetReturnTypeForSignature(property.Type);

                string name;
                string access;
                if (property.IsIndexer)
                {
                    var parameters = string.Join(", ", property.Parameters.Select(p =>
                        $"{ParameterModifier(p)}{Utils.GetReturnTypeForSignature(p.Type)} {Utils.ParameterIdentifier(p)}"));
                    name = $"this[{parameters}]";
                    access = $"{target}[{string.Join(", ", property.Parameters.Select(p => Utils.ParameterIdentifier(p)))}]";
                }
                else
                {
                    name = Utils.Identifier(property.Name);
                    access = $"{target}.{name}";
                }

                var unsafeModifier = IsPointerType(property.Type) || property.Parameters.Any(p => IsPointerType(p.Type)) ? "unsafe " : "";
                sb.AppendLine($"        {unsafeModifier}{byRef}{type} {declaring}.{name}");
                sb.AppendLine("        {");
                if (property.GetMethod != null)
                    sb.AppendLine(byRef.Length > 0 ? $"            get => ref {access};" : $"            get => {access};");
                if (property.SetMethod != null)
                {
                    sb.AppendLine(property.SetMethod.IsInitOnly
                        ? "            init => throw new global::System.NotSupportedException(\"An init-only property can't be set through the cached decorator.\");"
                        : $"            set => {access} = value;");
                }

                sb.AppendLine("        }");
                sb.AppendLine();
            }

            private static void EmitPassthroughEvent(StringBuilder sb, IEventSymbol @event)
            {
                var declaring = Utils.GetReturnTypeForSignature(@event.ContainingType);
                var name = Utils.Identifier(@event.Name);
                var target = $"(({declaring})this._decorated).{name}";
                sb.AppendLine($"        event {Utils.GetReturnTypeForSignature(@event.Type)} {declaring}.{name}");
                sb.AppendLine("        {");
                sb.AppendLine($"            add => {target} += value;");
                sb.AppendLine($"            remove => {target} -= value;");
                sb.AppendLine("        }");
                sb.AppendLine();
            }

            /// <summary>
            /// Emits an explicit implementation of the interface method. Explicit, so a method that two base interfaces
            /// both declare gets one implementation each, and so defaults, constraints and accessibility come from the
            /// interface instead of being repeated here.
            /// </summary>
            private static void EmitMethodSignature(StringBuilder sb, IMethodSymbol method, string modifiers = "")
            {
                var byRef = method.ReturnsByRefReadonly ? "ref readonly " : method.ReturnsByRef ? "ref " : string.Empty;
                var returnType = Utils.GetReturnTypeForSignature(method.ReturnType);
                var declaring = Utils.GetReturnTypeForSignature(method.ContainingType);
                var typeParams = method.TypeParameters.Any()
                    ? $"<{string.Join(", ", method.TypeParameters.Select(tp => Utils.TypeParameterIdentifier(tp)))}>"
                    : string.Empty;

                var parameters = string.Join(", ", method.Parameters.Select(p =>
                    $"{ParameterModifier(p)}{Utils.GetReturnTypeForSignature(p.Type)} {Utils.ParameterIdentifier(p)}"));

                var unsafeModifier = IsPointerType(method.ReturnType) || method.Parameters.Any(p => IsPointerType(p.Type)) ? "unsafe " : "";
                sb.AppendLine($"        {modifiers}{unsafeModifier}{byRef}{returnType} {declaring}.{Utils.Identifier(method.Name)}{typeParams}({parameters})");

                // An explicit implementation inherits the constraints; it may only say how T? reads. A type parameter
                // constrained to a class type (where T : Entity) is a reference type, and C# rejects `default` for it.
                foreach (var tp in method.TypeParameters)
                {
                    var clause = tp.HasReferenceTypeConstraint || tp.IsReferenceType ? "class"
                        : tp.HasValueTypeConstraint || tp.IsValueType ? "struct"
                        : "default";
                    sb.AppendLine($"            where {Utils.TypeParameterIdentifier(tp)} : {clause}");
                }
            }

            /// <summary>
            /// The parameter's modifiers as the interface declares them. <c>scoped</c> must match too, or the explicit
            /// implementation doesn't compile (CS8987); an <c>out</c> parameter is scoped implicitly.
            /// </summary>
            private static string ParameterModifier(IParameterSymbol parameter)
            {
                var scoped = parameter.ScopedKind != ScopedKind.None && parameter.RefKind != RefKind.Out ? "scoped " : string.Empty;
                return scoped + parameter.RefKind switch
                {
                    RefKind.Ref => "ref ",
                    RefKind.Out => "out ",
                    RefKind.In => "in ",
                    RefKind.RefReadOnlyParameter => "ref readonly ",
                    _ => string.Empty
                };
            }

            /// <summary>
            /// The call to the decorated instance, through the interface that declares the method, so a method two
            /// base interfaces both declare is never ambiguous.
            /// </summary>
            private static string BuildMethodCall(IMethodSymbol method, string target = "this._decorated")
            {
                var typeArgs = method.TypeParameters.Any()
                    ? $"<{string.Join(", ", method.TypeParameters.Select(tp => Utils.TypeParameterIdentifier(tp)))}>"
                    : string.Empty;

                var args = string.Join(", ", method.Parameters.Select(p =>
                {
                    // 'ref readonly' parameters are passed with 'in'
                    var modifier = p.RefKind switch
                    {
                        RefKind.Ref => "ref ",
                        RefKind.Out => "out ",
                        RefKind.In or RefKind.RefReadOnlyParameter => "in ",
                        _ => string.Empty
                    };
                    return modifier + Utils.ParameterIdentifier(p);
                }));

                var declaring = Utils.GetReturnTypeForSignature(method.ContainingType);
                return $"(({declaring}){target}).{Utils.Identifier(method.Name)}{typeArgs}({args})";
            }

            private static string BuildConstraints(ITypeParameterSymbol tp)
            {
                var constraints = new List<string>();

                if (tp.HasReferenceTypeConstraint)
                    constraints.Add("class");
                if (tp.HasUnmanagedTypeConstraint)
                    constraints.Add("unmanaged");
                else if (tp.HasValueTypeConstraint)
                    constraints.Add("struct");
                if (tp.HasNotNullConstraint)
                    constraints.Add("notnull");

                constraints.AddRange(ImmutableArrayExtensions.Select(tp.ConstraintTypes, ct => Utils.GetFullyQualifiedName(ct)));

                if (tp.HasConstructorConstraint && !tp.HasValueTypeConstraint && !tp.HasUnmanagedTypeConstraint)
                    constraints.Add("new()");

                if (Utils.AllowsRefLikeType(tp))
                    constraints.Add("allows ref struct");

                return constraints.Any()
                    ? $"where {Utils.TypeParameterIdentifier(tp)} : {string.Join(", ", constraints)}"
                    : string.Empty;
            }

        }

