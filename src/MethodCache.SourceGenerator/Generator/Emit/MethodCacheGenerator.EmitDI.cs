#nullable enable

using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace MethodCache.SourceGenerator
{
    public sealed partial class MethodCacheGenerator
    {
        // ======================== DI Extensions Emitter ========================
        private static class DIExtensionsEmitter
        {
            internal static string Emit(List<InterfaceInfo> interfaces)
            {
                var hasCachedMethods = interfaces.Any(i => i.CachedMethods.Length > 0);

                var sb = new StringBuilder();
                sb.AppendLine("// <auto-generated/>");
                sb.AppendLine("#nullable enable");
                sb.AppendLine("using System;");
                sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
                sb.AppendLine("using MethodCache;");
                sb.AppendLine("using MethodCache.Extensibility;");
                sb.AppendLine("using MethodCache.Infrastructure;");
                sb.AppendLine("using MethodCache.Policies;");
                if (hasCachedMethods)
                {
                    sb.AppendLine("using MethodCache.Generated;");
                }
                sb.AppendLine();
                sb.AppendLine("namespace Microsoft.Extensions.DependencyInjection");
                sb.AppendLine("{");
                // Internal: these helpers belong to the application, not to the public API of a library that uses MethodCache
                sb.AppendLine("    internal static class GeneratedCachingServiceCollectionExtensions");
                sb.AppendLine("    {");

                foreach (var info in interfaces.Where(i => !i.Symbol.IsGenericType))
                {
                    EmitInterfaceExtensions(sb, info, hasCachedMethods);
                }

                sb.AppendLine("    }");
                sb.AppendLine("}");

                return sb.ToString();
            }

            private static void EmitInterfaceExtensions(StringBuilder sb, InterfaceInfo info, bool hasAnyCachedMethods)
            {
                var interfaceFqn = Utils.GetFullyQualifiedName(info.Symbol);
                var decoratorFqn = Utils.GetDecoratorFullName(info.Symbol);
                var baseName = $"{info.Symbol.Name}WithCaching";

                var interfaceHasCachedMethods = info.CachedMethods.Length > 0;

                // Default (Singleton for backward compatibility)
                sb.AppendLine($"        internal static IServiceCollection Add{baseName}(");
                sb.AppendLine($"            this IServiceCollection services,");
                sb.AppendLine($"            Func<IServiceProvider, {interfaceFqn}> implementationFactory)");
                sb.AppendLine("        {");
                if (hasAnyCachedMethods && interfaceHasCachedMethods)
                {
                    sb.AppendLine("            GeneratedPolicyRegistrations.AddPolicies(services);");
                }
                sb.AppendLine($"            return services.AddSingleton<{interfaceFqn}>(sp =>");
                sb.AppendLine($"                new {decoratorFqn}(");
                sb.AppendLine("                    implementationFactory(sp),");
                sb.AppendLine("                    global::MethodCache.Infrastructure.DecoratorServices.From(sp)));");
                sb.AppendLine("        }");
                sb.AppendLine();

                // Explicit lifetime methods
                var lifetimes = new[] { ("Singleton", "AddSingleton"), ("Scoped", "AddScoped"), ("Transient", "AddTransient") };
                foreach (var (suffix, method) in lifetimes)
                {
                    sb.AppendLine($"        internal static IServiceCollection Add{baseName}{suffix}(");
                    sb.AppendLine($"            this IServiceCollection services,");
                    sb.AppendLine($"            Func<IServiceProvider, {interfaceFqn}> implementationFactory)");
                    sb.AppendLine("        {");
                    if (hasAnyCachedMethods && interfaceHasCachedMethods)
                    {
                        sb.AppendLine("            GeneratedPolicyRegistrations.AddPolicies(services);");
                    }
                    sb.AppendLine($"            return services.{method}<{interfaceFqn}>(sp =>");
                    sb.AppendLine($"                new {decoratorFqn}(");
                    sb.AppendLine("                    implementationFactory(sp),");
                    sb.AppendLine("                    global::MethodCache.Infrastructure.DecoratorServices.From(sp)));");
                    sb.AppendLine("        }");
                    sb.AppendLine();
                }
            }
        }
    }
}


