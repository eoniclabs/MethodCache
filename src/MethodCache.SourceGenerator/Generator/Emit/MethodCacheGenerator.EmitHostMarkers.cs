#nullable enable

using System.Linq;
using System.Text;
using MethodCache.Internal;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace MethodCache.SourceGenerator
{
    public sealed partial class MethodCacheGenerator
    {
        /// <summary>
        /// Marks the assembly when the project has cached services or calls AddMethodCache, so MC0030 in a program that
        /// references it can tell whether its cached services are set up. Each call is read on its own, so an edit
        /// elsewhere regenerates nothing.
        /// </summary>
        private static void RegisterHostMarkers(IncrementalGeneratorInitializationContext context, IncrementalValueProvider<bool> hasServices)
        {
            var calls = context.SyntaxProvider
                .CreateSyntaxProvider(
                    predicate: static (node, _) => HostMarkers.IsCandidate(node),
                    transform: static (ctx, ct) => HostMarkers.IsAddMethodCache(ctx.SemanticModel.GetSymbolInfo(ctx.Node, ct).Symbol))
                .Where(static calls => calls)
                .Collect()
                .Select(static (calls, _) => calls.Length > 0)
                .WithTrackingName(TrackingNames.HostMarkers);
            context.RegisterSourceOutput(hasServices.Combine(calls), static (ctx, input) => EmitHostMarkers(ctx, input.Left, input.Right));
        }

        private static void EmitHostMarkers(SourceProductionContext context, bool hasServices, bool callsAddMethodCache)
        {
            if (!hasServices && !callsAddMethodCache) return;

            var source = new StringBuilder()
                .AppendLine("// <auto-generated/>")
                .AppendLine("// Read by MethodCache's analyzer in the programs that reference this project, to tell whether their cached")
                .AppendLine("// services are set up with AddMethodCache.");
            foreach (var key in new[] { hasServices ? HostMarkers.CachedServices : null, callsAddMethodCache ? HostMarkers.CallsAddMethodCache : null }.Where(k => k != null))
            {
                source.Append("[assembly: global::System.Reflection.AssemblyMetadata(")
                    .Append(SymbolDisplay.FormatLiteral(key!, quote: true))
                    .AppendLine(", \"true\")]");
            }
            context.AddSource("MethodCacheHostMarkers.g.cs", source.ToString());
        }
    }
}
