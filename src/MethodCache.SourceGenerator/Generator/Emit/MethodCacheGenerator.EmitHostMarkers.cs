#nullable enable

using System.Linq;
using System.Text;
using MethodCache.Internal;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace MethodCache.SourceGenerator
{
    public sealed partial class MethodCacheGenerator
    {
        /// <summary>
        /// Marks the assembly when the project has cached services, and marks each method of the project that calls
        /// AddMethodCache, directly or through other setup methods, so MC0030 in a program that references it can tell
        /// whether the program sets up its cached services. Each call is read on its own, so an edit elsewhere
        /// regenerates nothing.
        /// </summary>
        private static void RegisterHostMarkers(IncrementalGeneratorInitializationContext context, IncrementalValueProvider<bool> hasServices)
        {
            var methods = context.SyntaxProvider
                .CreateSyntaxProvider(
                    predicate: static (node, _) => HostMarkers.IsCandidate(node),
                    transform: static (ctx, ct) => HostMarkers.Edge(ctx.SemanticModel, ctx.Node, ct))
                .Where(static edge => edge.HasValue)
                .Select(static (edge, _) => edge!.Value)
                .Collect()
                .Select(static (edges, _) => new EquatableArray<string>(HostMarkers.MarkedMethods(edges)))
                .WithTrackingName(TrackingNames.HostMarkers);
            context.RegisterSourceOutput(hasServices.Combine(methods), static (ctx, input) => EmitHostMarkers(ctx, input.Left, input.Right));
        }

        private static void EmitHostMarkers(SourceProductionContext context, bool hasServices, EquatableArray<string> addsMethodCache)
        {
            if (!hasServices && addsMethodCache.Count == 0) return;

            var source = new StringBuilder()
                .AppendLine("// <auto-generated/>")
                .AppendLine("// Read by MethodCache's analyzer in the programs that reference this project, to tell whether their cached")
                .AppendLine("// services are set up with AddMethodCache.");
            if (hasServices) Mark(HostMarkers.CachedServices, "true");
            foreach (var method in addsMethodCache) Mark(HostMarkers.AddsMethodCache, method);
            context.AddSource("MethodCacheHostMarkers.g.cs", source.ToString());

            void Mark(string key, string value)
                => source.Append("[assembly: global::System.Reflection.AssemblyMetadata(")
                    .Append(SymbolDisplay.FormatLiteral(key, quote: true))
                    .Append(", ")
                    .Append(SymbolDisplay.FormatLiteral(value, quote: true))
                    .AppendLine(")]");
        }
    }
}
