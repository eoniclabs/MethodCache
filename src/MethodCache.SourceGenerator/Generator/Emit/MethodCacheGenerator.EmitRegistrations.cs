#nullable enable

using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace MethodCache.SourceGenerator
{
    public sealed partial class MethodCacheGenerator
    {
        // ======================== Decorator Registrations Emitter ========================
        /// <summary>
        /// Emits a module initializer that registers this assembly's decorators with MethodCacheDecorators, so
        /// AddMethodCache() finds them without reflection over types.
        /// </summary>
        private static class DecoratorRegistrationsEmitter
        {
            internal static string Emit(List<InterfaceInfo> interfaces, ImmutableArray<INamedTypeSymbol?> classes)
            {
                var registrable = interfaces.Where(i => !i.Symbol.IsGenericType).ToList();
                if (registrable.Count == 0)
                {
                    return string.Empty;
                }

                var candidates = classes
                    .Where(c => c != null && IsAccessibleFromAssembly(c))
                    .Cast<INamedTypeSymbol>()
                    .Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default)
                    .ToList();

                var sb = new StringBuilder();
                sb.AppendLine("// <auto-generated/>");
                sb.AppendLine("#nullable enable");
                sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
                sb.AppendLine("using MethodCache.Abstractions.Registry;");
                sb.AppendLine("using MethodCache.Core.Infrastructure;");
                sb.AppendLine("using MethodCache.Core.Infrastructure.Registration;");
                sb.AppendLine("using MethodCache.Core.Runtime;");
                sb.AppendLine("using MethodCache.Core.Runtime.KeyGeneration;");
                sb.AppendLine();
                sb.AppendLine("namespace MethodCache.Generated");
                sb.AppendLine("{");
                sb.AppendLine("    [System.CodeDom.Compiler.GeneratedCode(\"MethodCacheGenerator\", \"1.0.0\")]");
                sb.AppendLine("    internal static class MethodCacheDecoratorRegistrations");
                sb.AppendLine("    {");
                sb.AppendLine("        [System.Runtime.CompilerServices.ModuleInitializer]");
                sb.AppendLine("        internal static void Register()");
                sb.AppendLine("        {");

                foreach (var info in registrable)
                {
                    var interfaceFqn = Utils.GetFullyQualifiedName(info.Symbol);
                    var decoratorFqn = Utils.GetDecoratorFullName(info.Symbol);
                    var hasPolicies = info.CachedMethods.Length > 0;
                    var implementation = FindImplementation(info.Symbol, candidates);

                    sb.AppendLine("            MethodCacheDecorators.Register(new DecoratorRegistration(");
                    sb.AppendLine($"                typeof({interfaceFqn}),");
                    sb.AppendLine($"                static (provider, inner) => new {decoratorFqn}(");
                    sb.AppendLine($"                    ({interfaceFqn})inner,");
                    sb.AppendLine("                    global::MethodCache.Core.Runtime.Core.DecoratorServices.From(provider)),");
                    sb.AppendLine(hasPolicies
                        ? "                GeneratedPolicyRegistrations.AddPolicies,"
                        : "                null,");
                    sb.AppendLine(implementation != null
                        ? $"                typeof({Utils.GetFullyQualifiedName(implementation)})));"
                        : "                null));");
                }

                sb.AppendLine("        }");
                sb.AppendLine("    }");
                sb.AppendLine("}");
                return sb.ToString();
            }

            /// <summary>
            /// Picks the class to register when the application has not registered the interface: the one named
            /// like the interface without its leading "I", otherwise the first by name. Only classes with a public
            /// constructor qualify, since the container needs one.
            /// </summary>
            private static INamedTypeSymbol? FindImplementation(INamedTypeSymbol interfaceSymbol, List<INamedTypeSymbol> candidates)
            {
                var matches = candidates
                    .Where(c => c.AllInterfaces.Contains(interfaceSymbol, SymbolEqualityComparer.Default))
                    .Where(c => c.InstanceConstructors.Any(ctor => ctor.DeclaredAccessibility == Accessibility.Public))
                    .OrderBy(c => c.ToDisplayString(), StringComparer.Ordinal)
                    .ToList();

                if (matches.Count == 0)
                {
                    return null;
                }

                var preferredName = interfaceSymbol.Name.StartsWith("I", StringComparison.Ordinal)
                    ? interfaceSymbol.Name.Substring(1)
                    : interfaceSymbol.Name;

                return matches.FirstOrDefault(c => c.Name == preferredName) ?? matches[0];
            }

            private static bool IsAccessibleFromAssembly(INamedTypeSymbol? type)
            {
                for (var current = type; current != null; current = current.ContainingType)
                {
                    if (current.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal or Accessibility.ProtectedOrInternal))
                    {
                        return false;
                    }
                }

                return type != null;
            }
        }
    }
}
