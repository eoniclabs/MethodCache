#nullable enable

using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace MethodCache.SourceGenerator
{
    public sealed partial class MethodCacheGenerator
    {
        // ======================== Decorator Registrations Emitter ========================
        /// <summary>
        /// Emits the stable bootstrap and a descriptor for this assembly. Startup chooses bindings
        /// without reflecting over service implementation types.
        /// </summary>
        private static class DecoratorRegistrationsEmitter
        {
            internal static string Emit(IReadOnlyList<InterfaceSummary> interfaces, EquatableArray<ClassInfo> classes)
            {
                // A partial class is declared, and so found, more than once
                var allClasses = classes
                    .GroupBy(c => c.Fqn, StringComparer.Ordinal)
                    .Select(g => g.First())
                    .ToList();
                var candidates = allClasses.Where(c => c.IsAccessible).ToList();

                // A generic interface is registered once per closed type the assembly implements, such as
                // IRepository<User> for UserRepository : IRepository<User>. Private classes count too, since the
                // application can still register them through a factory
                var registrable = new List<(InterfaceSummary Info, string ServiceFqn, EquatableArray<string> TypeArguments)>();
                foreach (var info in interfaces)
                {
                    if (!info.IsGeneric)
                    {
                        registrable.Add((info, info.InterfaceFqn, EquatableArray<string>.Empty));
                        continue;
                    }

                    var closedTypes = allClasses
                        .SelectMany(c => c.Interfaces)
                        .Where(i => i.AssemblyIdentity == info.AssemblyIdentity && i.OriginalDefinitionFqn == info.OriginalDefinitionFqn && i.IsNameable)
                        .GroupBy(i => i.Fqn, StringComparer.Ordinal)
                        .Select(g => g.First())
                        .OrderBy(i => i.DisplayName, StringComparer.Ordinal);
                    foreach (var closed in closedTypes)
                    {
                        registrable.Add((info, closed.Fqn, closed.TypeArgumentFqns));
                    }
                }

                if (interfaces.Count == 0)
                {
                    return string.Empty;
                }

                var sb = new StringBuilder();
                sb.AppendLine("// <auto-generated/>");
                sb.AppendLine("#nullable enable");
                sb.AppendLine("namespace MethodCache.Generated");
                sb.AppendLine("{");
                sb.AppendLine($"    [global::System.CodeDom.Compiler.GeneratedCode(\"MethodCacheGenerator\", {Utils.Literal(typeof(MethodCacheGenerator).Assembly.GetName().Version!.ToString())})]");
                sb.AppendLine("    internal static partial class MethodCacheDecoratorRegistrations");
                sb.AppendLine("    {");
                sb.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
                sb.AppendLine("        internal static void Register() => global::MethodCache.Generated.GeneratedCode.Register(1, new Module());");
                sb.AppendLine("        private sealed class Module : global::MethodCache.Generated.GeneratedModule");
                sb.AppendLine("        {");
                sb.AppendLine("            public override void Describe(global::MethodCache.Generated.GeneratedModuleBuilder builder)");
                sb.AppendLine("            {");
                foreach (var info in interfaces)
                    sb.AppendLine($"                builder.DeclareService(typeof({info.UnboundInterfaceFqn}));");
                if (interfaces.Any(i => i.HasCachedMethods))
                    sb.AppendLine("                GeneratedPolicyRegistrations.Describe(builder);");

                foreach (var (info, interfaceFqn, typeArguments) in registrable)
                {
                    var decoratorFqn = info.DecoratorFqn;
                    if (typeArguments.Count > 0)
                    {
                        decoratorFqn += "<" + string.Join(", ", typeArguments) + ">";
                    }

                    sb.AppendLine("                builder.Decorator(");
                    sb.AppendLine($"                    typeof({interfaceFqn}),");
                    sb.AppendLine($"                    static (inner, services) => new {decoratorFqn}(({interfaceFqn})inner, services),");
                    sb.AppendLine($"                    new string[] {{ {string.Join(", ", info.Policies.Select(p => Utils.Literal(p.MethodId)))} }});");
                    foreach (var candidate in candidates.Where(c => c.HasPublicConstructor && c.Interfaces.Any(i => i.AssemblyIdentity == info.AssemblyIdentity && i.Fqn == interfaceFqn)))
                        sb.AppendLine($"                builder.ImplementationCandidate(typeof({interfaceFqn}), typeof({candidate.Fqn}));");
                }

                sb.AppendLine("            }");
                sb.AppendLine("        }");
                sb.AppendLine("    }");
                sb.AppendLine("}");
                return sb.ToString();
            }

            /// <summary>Whether generated code in <paramref name="assembly"/> can name the type, including its type arguments.</summary>
            internal static bool IsNameableFrom(ITypeSymbol type, IAssemblySymbol assembly) => type switch
            {
                IArrayTypeSymbol array => IsNameableFrom(array.ElementType, assembly),
                INamedTypeSymbol named => (SymbolEqualityComparer.Default.Equals(named.ContainingAssembly, assembly)
                                              ? IsAccessibleFromAssembly(named)
                                              : IsPublic(named))
                                          && Utils.AllTypeArguments(named).All(t => IsNameableFrom(t, assembly)),
                _ => false,
            };

            private static bool IsPublic(INamedTypeSymbol type)
            {
                for (var current = type; current != null; current = current.ContainingType)
                {
                    if (current.DeclaredAccessibility != Accessibility.Public)
                    {
                        return false;
                    }
                }

                return true;
            }

            /// <summary>
            /// Whether generated code in the type's own assembly can name it. A <c>file</c> class reports internal
            /// accessibility but can only be named from its own file.
            /// </summary>
            internal static bool IsAccessibleFromAssembly(INamedTypeSymbol? type)
            {
                for (var current = type; current != null; current = current.ContainingType)
                {
                    if (current.IsFileLocal ||
                        current.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal or Accessibility.ProtectedOrInternal))
                    {
                        return false;
                    }
                }

                return type != null;
            }
        }
    }
}
